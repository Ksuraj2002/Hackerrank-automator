r"""Build the automator-ready markdown from authored specs.

  venv\Scripts\python.exe tools\build_md.py                 # only items in out/missing.json
  venv\Scripts\python.exe tools\build_md.py --all            # every codeable curriculum item
  venv\Scripts\python.exe tools\build_md.py --keys lc53,...  # a chosen subset

Every sample output is computed by the spec's reference solution, so statements
and samples cannot drift apart. Items with no spec in problem_bank.py are listed
as TODO rather than emitted as filler.
"""
import argparse
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import diff_challenges as dc  # noqa: E402  (reuse the drill/theory filter)
from problem_bank import BANK, lc_url  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT_DIR = os.path.join(ROOT, "tools", "out")


def render(spec, item):
    title = "%s: %s" % (item["kind"], spec["title"])
    statement = spec["statement"]
    if spec.get("lc"):
        url = lc_url(spec["lc"])
        if not url:
            raise SystemExit("spec %r has lc=%s but no slug in LC_SLUGS"
                             % (spec["title"], spec["lc"]))
        statement = ("**LeetCode LC%d** - original problem: %s\n\n%s"
                     % (spec["lc"], url, statement))

    parts = ["## %s" % title,
             "**Problem Statement**", statement, "",
             "**Input Format**", spec["input_fmt"], "",
             "**Output Format**", spec["output_fmt"], "",
             "**Constraints**", spec["constraints"], ""]
    for i, sample in enumerate(spec["samples"]):
        parts += ["**Sample Input %d**" % i, "```", sample, "```", "",
                  "**Sample Output %d**" % i, "```", spec["solve"](sample), "```", ""]
    parts += ["**Tags**", ", ".join(spec["tags"]), "", "---", ""]
    return "\n".join(parts)


def load_items(args):
    if args.all or args.keys:
        src = os.path.join(OUT_DIR, "curriculum_questions.json")
        with open(src, encoding="utf-8") as f:
            items = [i for i in json.load(f) if dc.is_challenge(i["text"])]
        if args.keys:
            wanted = {k.strip() for k in args.keys.split(",")}
            items = [i for i in items if i["key"] in wanted]
        return items

    src = args.source or os.path.join(OUT_DIR, "missing.json")
    if not os.path.exists(src):
        raise SystemExit("No %s - run hr_list_challenges.py then diff_challenges.py, "
                         "or pass --all / --keys / --from." % src)
    with open(src, encoding="utf-8") as f:
        items = json.load(f)
    # sheet_delta.py output carries a status; build only what is actually absent.
    if items and "status" in items[0]:
        items = [i for i in items if i["status"] in ("create", "absent")]
    return items


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--all", action="store_true")
    ap.add_argument("--keys")
    ap.add_argument("--from", dest="source",
                    help="question list to build from (default tools/out/missing.json)")
    ap.add_argument("--out", default=os.path.join(ROOT, "DSA101_Challenges.md"))
    args = ap.parse_args()

    items = load_items(args)

    # The sheet repeats questions across revision days; emit each key once.
    seen, unique = set(), []
    for it in items:
        if it["key"] in seen:
            continue
        seen.add(it["key"])
        unique.append(it)

    body, todo, day, written = [], [], None, 0
    for it in unique:
        spec = BANK.get(it["key"])
        if not spec:
            todo.append(it)
            continue
        if it["day"] != day:
            day = it["day"]
            body.append("# %s - %s\n" % (day, it["lecture_name"]))
        # One curriculum line can carry more than one problem (e.g. the
        # CodingBat "chocolates and bricks" item), so a spec may be a list.
        for one in (spec if isinstance(spec, list) else [spec]):
            body.append(render(one, it))
            written += 1

    header = ("# DSA-101 HackerRank Challenges\n\n"
              "Generated by `tools/build_md.py` from *Standardised Curricullum.xlsx*. "
              "Sample outputs are computed by the reference solutions in "
              "`tools/problem_bank.py`. Section format matches the parser in "
              "`automator.py`.\n\n---\n\n")
    with open(args.out, "w", encoding="utf-8") as f:
        f.write(header + "\n".join(body))

    with open(os.path.join(OUT_DIR, "todo_specs.txt"), "w", encoding="utf-8") as f:
        for it in todo:
            f.write("%-24s %-7s %-9s %s\n" % (it["key"], it["day"], it["kind"], it["text"][:100]))

    print("unique questions in scope: %d" % len(unique))
    print("  challenges written to %s: %d" % (os.path.relpath(args.out, ROOT), written))
    print("  awaiting a spec:          %d  (tools/out/todo_specs.txt)" % len(todo))


if __name__ == "__main__":
    main()
